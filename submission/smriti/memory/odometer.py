"""Calibrated dead reckoning; no environment, privileged state, or policy decisions.

Call update with the action executed and its resulting NONTERMINAL observation.
The reset observation is not a transition. Coordinates are map units in the spawn
frame: +x initially forward, +y initially left, heading positive counterclockwise.
"""
from __future__ import annotations

from dataclasses import dataclass
from importlib.metadata import version
import json
import math
from pathlib import Path

import numpy as np

DEFAULT_CALIBRATION = Path(__file__).with_name('calibration.json')


def _finite(value, name):
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f'{name} must be finite') from exc
    if not math.isfinite(number):
        raise ValueError(f'{name} must be finite')
    return number


@dataclass(frozen=True)
class Calibration:
    """Validated immutable calibration, generated by scripts/measure_odometry.py."""
    buttons: tuple[str, ...]
    vitals_fields: tuple[str, ...]
    left: tuple[float, ...]
    right: tuple[float, ...]
    first_left: float
    first_right: float
    second_left: tuple[float, float]
    second_right: tuple[float, float]
    a_now: float
    b_prev: float

    @classmethod
    def load(cls, path: str | Path = DEFAULT_CALIBRATION) -> Calibration:
        return cls.from_dict(json.loads(Path(path).read_text(encoding='utf-8')))

    @classmethod
    def from_dict(cls, data: dict) -> Calibration:
        try:
            if data['schema_version'] != 1 or data['frame_skip'] != 4:
                raise ValueError('unsupported calibration schema or frame skip')
            if data['engine_version'] != version('vizdoom'):
                raise ValueError('calibration does not match installed ViZDoom')
            if data['contract_version'] != '1.0.0-draft':
                raise ValueError('unsupported observation contract')
            buttons = tuple(data['buttons'])
            vitals = tuple(data['vitals_fields'])
            # Contract metadata, not fitted movement coefficients. Do not silently accept reordered inputs.
            expected_buttons = ('MOVE_FORWARD', 'MOVE_BACKWARD', 'MOVE_LEFT', 'MOVE_RIGHT',
                                'TURN_LEFT', 'TURN_RIGHT', 'ATTACK', 'USE', 'SELECT_NEXT_WEAPON')
            if buttons != expected_buttons or len(vitals) != 17 or vitals[14:] != ('vel_forward', 'vel_right', 'vel_up'):
                raise ValueError('calibration action/observation layout does not match contract')
            turns = data['turns']
            sequences = {}
            for key in ('left', 'right', 'second_left', 'second_right'):
                seq = tuple(_finite(x, key) for x in turns[key])
                if not seq or (key.startswith('second') and len(seq) != 2):
                    raise ValueError(f'invalid turn sequence: {key}')
                if any(x <= 0 for x in seq) if key.endswith('left') else any(x >= 0 for x in seq):
                    raise ValueError(f'invalid turn direction: {key}')
                sequences[key] = seq
            return cls(buttons, vitals, sequences['left'], sequences['right'],
                       _finite(turns['first_left'], 'first_left'), _finite(turns['first_right'], 'first_right'),
                       sequences['second_left'], sequences['second_right'],
                       _finite(data['motion']['a_now'], 'a_now'), _finite(data['motion']['b_prev'], 'b_prev'))
        except (KeyError, TypeError) as exc:
            raise ValueError('incomplete calibration') from exc


@dataclass(frozen=True)
class Pose:
    x: float = 0.0
    y: float = 0.0
    heading_deg: float = 0.0


class Odometer:
    def __init__(self, calibration: Calibration | None = None):
        self.calibration = Calibration.load() if calibration is None else calibration
        self._left = self.calibration.buttons.index('TURN_LEFT')
        self._right = self.calibration.buttons.index('TURN_RIGHT')
        self._forward = self.calibration.vitals_fields.index('vel_forward')
        self._strafe = self.calibration.vitals_fields.index('vel_right')
        self.reset()

    def reset(self) -> None:
        self.pose = Pose()
        self.steps = 0
        self._held = 0
        self._previous_velocity = np.zeros(2, dtype=np.float64)

    def update(self, action: np.ndarray, observation: dict) -> Pose:
        """Consume one executed transition; reject invalid input without changing state."""
        try:
            action = np.asarray(action, dtype=np.float64)
            vitals = np.asarray(observation['vitals'], dtype=np.float64)
        except (KeyError, TypeError, ValueError, OverflowError) as exc:
            raise ValueError('invalid odometer transition') from exc
        if action.shape != (len(self.calibration.buttons),) or not np.all((action == 0) | (action == 1)):
            raise ValueError('action must match the binary button contract')
        if vitals.shape != (len(self.calibration.vitals_fields),) or not np.isfinite(vitals).all():
            raise ValueError('vitals must match the finite observation contract')
        left, right = bool(action[self._left]), bool(action[self._right])
        previous_turn = self._held > 0
        held = self._held + 1 if left or right else 0
        delta = 0.0
        c = self.calibration
        if left != right:
            sequence = c.left if left else c.right
            if self.steps == 0:
                delta = c.first_left if left else c.first_right
            elif self.steps == 1:
                delta = (c.second_left if left else c.second_right)[int(previous_turn)]
            else:
                delta = sequence[min(held, len(sequence)) - 1]
        heading = (self.pose.heading_deg + delta + 180.0) % 360.0 - 180.0
        h = math.radians(heading)
        forward, rightward = vitals[self._forward], vitals[self._strafe]
        velocity = np.array([forward * math.cos(h) + rightward * math.sin(h),
                             forward * math.sin(h) - rightward * math.cos(h)])
        displacement = c.a_now * velocity + c.b_prev * self._previous_velocity
        pose = Pose(self.pose.x + float(displacement[0]), self.pose.y + float(displacement[1]), heading)
        if not all(math.isfinite(x) for x in (pose.x, pose.y, pose.heading_deg)):
            raise ValueError('odometer transition overflowed')
        self.pose, self._held = pose, held
        self._previous_velocity = velocity
        self.steps += 1
        return pose
